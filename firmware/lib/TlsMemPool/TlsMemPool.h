// mbedTLSの確保/解放を専用の固定プールへ隔離する(docs/design.md
// 「mbedTLS専用固定プール化」案の本実装、2026-08-10)。
//
// 動機: `namzwire::newBatch()`(=`Batch`のmalloc())が、ヒープに十分な空きが
// あるように見えても失敗する現象を実機で繰り返し踏んだ(PR #54)。実機で
// 直接再現・確認した原因は、TLS接続を使い回している間mbedTLSが握ったまま
// 解放しないセッション状態(実測ピーク約48KB)が一般ヒープの連続した空き
// 領域を奪い、newBatch()の18KB要求を通せなくすること
// (docs/log/2026-08-10-tls-dedicated-pool.md、firmware/lib/TlsAllocProbeで
// 計測)。実機では`malloc(18032)`が指数バックオフの上限(60秒)に達しても
// 延々と失敗し続け、パニックもクラッシュもしないまま外からは「無応答」に
// しか見えない状態を再現した。
//
// 対策: mbedTLSの確保/解放だけを一般ヒープから隔離し、専用の固定領域を
// 使わせる。一般ヒープを奪い合わなくなるので、newBatch()側はTLSの都合に
// 影響されなくなる。プールが尽きた場合はcalloc失敗として返す
// （mbedTLS自身が想定している経路——TLS操作が失敗し、呼び出し側の
// 既存の指数バックオフに委ねられるだけで安全に縮退する。一般ヒープは
// 一切奪わない）。
//
// プールは起動時にmalloc()で一度だけ確保する（static配列にしない）。
// static配列は`dram0_0_seg`のリンク時静的配置制限(~121KB、既存の静的領域
// だけで既に大半を使用済み)に当たる。setup()の早い段階でのmalloc()一発
// 確保ならこの制限を受けない(PR #54のバッチバッファプールで実証済み)。
//
// フックはmbedTLSライブラリ全体に対してプロセス単位でしか差し替えられない
// （コネクション単位ではない）ため、install()以降に走る全mbedTLS呼び出し
// ——Uploaderのingest/alert接続だけでなく、将来のOTA(docs/ota.md)のTLSも——
// が対象になる。design.mdの前提通り「TLS接続は同時に1本」なら競合しない
// （OTA実装時にこの前提が崩れないかは要確認）。単一のuploaderTaskからしか
// 呼ばれない前提でロックは持たない。

